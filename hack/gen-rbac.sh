#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
"${CONTROLLER_GEN:-./bin/controller-gen}" rbac:roleName=herzi paths=./internal/controller/... output:rbac:stdout | python3 -c '
import sys,yaml
from pathlib import Path
roles=[d for d in yaml.safe_load_all(sys.stdin) if d and d.get("kind")=="ClusterRole"]
assert len(roles)==1, "expected one generated ClusterRole"
path=Path("charts/herzi/files/rbac-rules.yaml")
expected="# GENERATED by hack/gen-rbac.sh from the +kubebuilder:rbac markers — do not edit\n"+yaml.safe_dump(roles[0]["rules"],sort_keys=False)
if sys.argv[1:] == ["--check"]:
    assert path.read_text()==expected, "manager RBAC drift; run make manifests"
    print("Generated RBAC matches chart")
else:
    path.write_text(expected)
' "$@"
