#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
./bin/controller-gen rbac:roleName=herzi paths=./internal/controller/... output:rbac:stdout | python3 -c '
import sys,yaml
from pathlib import Path
roles=[d for d in yaml.safe_load_all(sys.stdin) if d and d.get("kind")=="ClusterRole"]
assert len(roles)==1, "expected one generated ClusterRole"
Path("charts/herzi/files/rbac-rules.yaml").write_text("# GENERATED by hack/gen-rbac.sh from the +kubebuilder:rbac markers — do not edit\n"+yaml.safe_dump(roles[0]["rules"],sort_keys=False))
'
